@pytest.mark.parametrize(
    "fixture_directory",
    (FIXTURE_DIRECTORY, NATIVE_FIXTURE_DIRECTORY),
    ids=("witness-shards", "native-job-set"),
)
def test_fixture_workflow_digests_bind_the_actual_workflow_bytes(
    fixture_directory: Path,
) -> None:
    source = json.loads((fixture_directory / "target-artifacts-source.v1.json").read_bytes())
    registry = json.loads((fixture_directory / "execution-registry.v1.json").read_bytes())
    source_bindings = {
        str(_object(item)["path"]): str(_object(item)["sha256"])
        for item in _array(source["adapterWorkflowFiles"])
    }
    registry_bindings = {
        str(_object(item)["path"]): str(_object(item)["sha256"])
        for item in _array(registry["adapterFiles"])
        if str(_object(item)["path"]) in source_bindings
    }
    repository_root = fixture_directory.parent

    assert registry_bindings == source_bindings
    assert {
        path: digest_adapter_file((repository_root / path).read_bytes()) for path in source_bindings
    } == source_bindings


