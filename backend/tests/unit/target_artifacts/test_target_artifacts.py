def test_fixture_source_renders_runtime_admitted_schema_valid_artifacts() -> None:
    source = parse_target_artifacts_source(SOURCE_PATH.read_bytes())
    rendered = render_target_artifacts(source)
    registry = parse_target_execution_registry(rendered.execution_registry)

    assert registry is not None
    workflow = registry.workflows[0]
    assert workflow.plan_request_job_id == PLAN_REQUEST_JOB_ID
    assert workflow.plan_request_workflow_ref == PLAN_REQUEST_WORKFLOW_REF
    assert rendered.control_bundle.startswith(
        b"// Generated by scripts.target_control_bundle; do not edit; source-sha256="
    )
    assert parse_test_manifest(rendered.test_manifest) is not None
    assert (
        parse_dependency_graph_artifact(
            rendered.dependency_graph,
            retrieved_for_sha="a" * 40,
            trusted=True,
        )
        is not None
    )
    for schema_name, value in (
        ("target-artifacts-source.schema.v1.json", json.loads(SOURCE_PATH.read_bytes())),
        (
            "target-execution-registry.schema.v1.json",
            json.loads(rendered.execution_registry),
        ),
        ("test-manifest.schema.v1.json", json.loads(rendered.test_manifest)),
        ("dependency-graph.schema.v1.json", json.loads(rendered.dependency_graph)),
        (
            "plan-trust-root.schema.v1.json",
            json.loads((FIXTURE_DIRECTORY / "plan-trust-root.v1.json").read_bytes()),
        ),
    ):
        schema = json.loads((SCHEMA_DIRECTORY / schema_name).read_bytes())
        Draft202012Validator.check_schema(schema)
        Draft202012Validator(schema).validate(value)


