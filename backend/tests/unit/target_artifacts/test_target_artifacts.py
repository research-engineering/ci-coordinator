@pytest.mark.parametrize(("count", "admitted"), [(16, True), (17, False)])
def test_service_profile_bound_matches_source_and_registry_admission(
    count: int,
    admitted: bool,
) -> None:
    service_profile_ids = [f"service-{index:02d}" for index in range(count)]
    source = json.loads(SOURCE_PATH.read_bytes())
    _object(_array(source["executionProfiles"])[0])["serviceProfileIds"] = service_profile_ids
    registry = json.loads((FIXTURE_DIRECTORY / "execution-registry.v1.json").read_bytes())
    _object(_array(registry["profiles"])[0])["serviceProfileIds"] = service_profile_ids

    if admitted:
        parsed_source = parse_target_artifacts_source(json.dumps(source).encode())
        assert (
            parse_target_execution_registry(
                render_target_artifacts(parsed_source).execution_registry
            )
            is not None
        )
        assert parse_target_execution_registry(json.dumps(registry).encode()) is not None
    else:
        with pytest.raises(TargetArtifactsAdmissionError):
            parse_target_artifacts_source(json.dumps(source).encode())
        assert parse_target_execution_registry(json.dumps(registry).encode()) is None


