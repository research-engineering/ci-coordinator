def test_write_and_check_modes_detect_exact_byte_drift(tmp_path: Path) -> None:
    source = tmp_path / "source.json"
    source.write_bytes(SOURCE_PATH.read_bytes())
    source.chmod(0o640)
    authored = tmp_path / "authored.txt"
    authored.write_bytes(b"Authored input must survive artifact generation.\n")
    output = tmp_path / "generated"

    def snapshot() -> dict[str, tuple[int, int, bytes]]:
        return {
            path.relative_to(tmp_path).as_posix(): (
                path.lstat().st_mode,
                path.lstat().st_mtime_ns,
                path.read_bytes(),
            )
            for path in tmp_path.rglob("*")
            if path.is_file() or path.is_symlink()
        }

    authored_before = snapshot()
    rendered = render_target_artifacts(parse_target_artifacts_source(source.read_bytes()))
    expected_outputs = (
        "execution-registry.v1.json",
        "test-manifest.v1.json",
        "dependency-graph.v1.json",
        "ci-coordinator.cjs",
    )
    assert check_artifacts(output, rendered) == expected_outputs
    assert snapshot() == authored_before

    write_artifacts(output, rendered)
    after_write = snapshot()
    assert set(after_write) == set(authored_before) | {
        f"generated/{name}" for name in expected_outputs
    }
    assert {path: after_write[path] for path in authored_before} == authored_before
    assert check_artifacts(output, rendered) == ()
    assert snapshot() == after_write

    (output / "test-manifest.v1.json").write_text("{}\n")
    assert check_artifacts(output, rendered) == ("test-manifest.v1.json",)


