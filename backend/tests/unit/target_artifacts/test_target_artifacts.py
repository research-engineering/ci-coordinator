def test_failed_replacement_removes_the_temporary_file(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    rendered = render_target_artifacts(parse_target_artifacts_source(SOURCE_PATH.read_bytes()))

    def reject_replace(_source: Path, _target: Path) -> Path:
        raise OSError("replacement failed")

