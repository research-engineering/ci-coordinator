def test_plan_trust_root_cli_renders_and_checks_exact_ed25519_identity(
    tmp_path: Path,
    capsys: pytest.CaptureFixture[str],
) -> None:
    public_key = tmp_path / "plan-signing.pub.pem"
    output = tmp_path / "plan-trust-root.v1.json"
    public_key.write_bytes(
        ed25519.Ed25519PrivateKey.generate()
        .public_key()
        .public_bytes(Encoding.PEM, PublicFormat.SubjectPublicKeyInfo)
    )
    arguments = [
        "--key-id",
        "release-key.2026-07",
        "--public-key",
        str(public_key),
        "--output",
        str(output),
    ]

    assert main(["check-trust-root", *arguments]) == 1
    assert "plan_trust_root_drift" in capsys.readouterr().err
    assert main(["render-trust-root", *arguments]) == 0
    assert "plan_trust_root_rendered" in capsys.readouterr().out
    expected = render_plan_trust_root(
        key_id="release-key.2026-07",
        public_key_pem=public_key.read_bytes(),
    )
    assert output.read_bytes() == expected
    assert check_plan_trust_root(output, expected)
    assert main(["check-trust-root", *arguments]) == 0
    assert "plan_trust_root_current" in capsys.readouterr().out


def test_plan_trust_root_rejects_non_ed25519_and_symlinked_artifacts(tmp_path: Path) -> None:
    rsa_key = rsa.generate_private_key(public_exponent=65537, key_size=2048).public_key()
    with pytest.raises(ValueError, match="Ed25519"):
        render_plan_trust_root(
            key_id="rsa-key",
            public_key_pem=rsa_key.public_bytes(Encoding.PEM, PublicFormat.SubjectPublicKeyInfo),
        )

    target = tmp_path / "target.json"
    link = tmp_path / "plan-trust-root.v1.json"
    target.write_bytes(b"{}\n")
    link.symlink_to(target)
    assert not check_plan_trust_root(link, b"{}\n")


def _enlarge_manifest(source: dict[str, object]) -> None:
    tests = _array(source["tests"])
    witness_id = _object(tests[0])["witnessId"]
    source["tests"] = [
        {
            "testId": f"{index:04d}-" + "x" * 240,
            "witnessId": witness_id,
            "expectedSeconds": 1,
        }
        for index in range(4_096)
    ]


def _object(value: object) -> dict[str, object]:
    assert isinstance(value, dict)
    return value


def _array(value: object) -> list[object]:
    assert isinstance(value, list)
    return value


def test_render_rejects_test_manifest_byte_overflow_before_write() -> None:
    source = json.loads(SOURCE_PATH.read_bytes())
